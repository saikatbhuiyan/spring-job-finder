/**
 * The OpenAPI document of {@code /api/**} (docs/adr/0016-openapi-documentation.md), generated by
 * springdoc-openapi from the controllers, and corrected where springdoc can't see the API's contract.
 * Measured before this class: paths as {@code /api/1/...}, {@link PageQuery} as an object with a
 * {@code sort} of {@code {empty, sorted, unsorted}}, no error responses at all, no {@code Idempotency-Key}.
 *
 * <p>Deliberately not a {@code WebMvcConfigurer}: slices must not pick it up (ADR 0015).
 */
@Configuration(proxyBeanMethods = false)
class OpenApiConfig {

    static final String PROBLEM_SCHEMA = "Problem";
    static final String VIOLATION_SCHEMA = "Violation";
    static final String PROBLEM_JSON = "application/problem+json";

    /** Reusable responses, also for controllers: {@code @ApiResponse(responseCode = "404", ref = NOT_FOUND)}. */
    static final String BAD_REQUEST = "BadRequest";
    static final String NOT_FOUND = "NotFound";
    static final String CONFLICT = "Conflict";
    static final String CONTENT_TOO_LARGE = "ContentTooLarge";
    static final String IDEMPOTENCY_KEY_REUSED = "IdempotencyKeyReused";
    static final String REQUEST_IN_PROGRESS = "RequestInProgress";
    static final String TOO_MANY_REQUESTS = "TooManyRequests";
    static final String SERVER_ERROR = "ServerError";

    private static final String RESPONSES = "#/components/responses/";
    private static final String DOCS = "https://github.com/saikatbhuiyan/spring-job-finder/blob/main/docs/";

    /** Spring's path versioning maps {@code /api/{version}/...}; springdoc substitutes the bare version. */
    private static final Pattern BARE_VERSION = Pattern.compile("^/api/(\\d+(?:\\.\\d+)*)/");

    static {
        // Bound by PageQueryArgumentResolver, not by Spring's data binder: springdoc would document its
        // record components (and Sort as {empty, sorted, unsorted}). The real parameters are added below.
        SpringDocUtils.getConfig().addRequestWrapperToIgnore(PageQuery.class);
    }

    @Bean
    OpenAPI jobFinderOpenApi() {
        return new OpenAPI()
                .info(new Info()
                        .title("Job Finder API")
                        .version("1")
                        .description("""
                                Job-search REST API. Conventions that apply to every operation:

                                - **Errors** are RFC 9457 Problem Details (`application/problem+json`); \
                                compare on `type` ([catalogue](%1$sproblems.md)). Every response carries the \
                                request's trace ID in `X-Trace-Id`, and every problem as `traceId`: quote it \
                                when reporting an error.
                                - **Unknown properties and query parameters are rejected** (`400`), so a \
                                typo is never silently ignored. JSON types are strict: `"5"` is not a number.
                                - **Rate limit**: over the limit, `429` with `Retry-After` (seconds).
                                - **Retries**: `POST`/`PATCH` accept an `Idempotency-Key`; a retry with the \
                                same key gets the first response again (`Idempotent-Replayed: true`).
                                """.formatted(DOCS)))
                // Relative: the server that served this document, whatever host or proxy is in front.
                .servers(List.of(new Server().url("/")))
                .components(new Components()
                        .addSchemas(VIOLATION_SCHEMA, violationSchema())
                        .addSchemas(PROBLEM_SCHEMA, problemSchema())
                        .addResponses(BAD_REQUEST, problem("The request is invalid: see `errors` for each field or "
                                + "parameter (`validation-error`), or the body isn't valid JSON (`malformed-request-body`)."))
                        .addResponses(NOT_FOUND, problem("The resource doesn't exist (`resource-not-found`)."))
                        .addResponses(CONFLICT, problem("The request conflicts with the resource's state (`conflict`)."))
                        .addResponses(CONTENT_TOO_LARGE, problem("A request body sent with an `Idempotency-Key` is "
                                + "larger than 1 MB."))
                        .addResponses(IDEMPOTENCY_KEY_REUSED, problem("The `Idempotency-Key` was already used for a "
                                + "different request (`idempotency-key-reused`)."))
                        .addResponses(REQUEST_IN_PROGRESS, problem("A request with this `Idempotency-Key` is still being "
                                + "processed (`request-in-progress`); retry after `Retry-After` seconds.")
                                .addHeaderObject("Retry-After", retryAfter()))
                        .addResponses(TOO_MANY_REQUESTS, problem("Too many requests from this client; retry after "
                                + "`Retry-After` seconds.").addHeaderObject("Retry-After", retryAfter()))
                        .addResponses(SERVER_ERROR, problem("An unexpected error. Nothing about the cause is "
                                + "revealed: report the `traceId`.")));
    }

    /**
     * What every {@code /api} operation shares, from how the request pipeline works: the trace ID on
     * every response, a {@code 400}/{@code 429}/{@code 500} from any operation (unknown parameters are
     * rejected everywhere, the rate limit covers all of {@code /api}), the paging parameters, and the
     * idempotency key on {@code POST}/{@code PATCH}. Responses an operation declares itself are kept.
     */
    @Bean
    OperationCustomizer apiConventions() {
        return (operation, handler) -> {
            for (MethodParameter parameter : handler.getMethodParameters()) {
                if (PageQuery.class.equals(parameter.getParameterType())) {
                    pagingParameters(parameter.getParameterAnnotation(SortableBy.class)).forEach(operation::addParametersItem);
                }
            }
            ApiResponses responses = operation.getResponses(); // springdoc always sets at least the default 200
            if (acceptsIdempotencyKey(handler)) {
                boolean required = AnnotatedElementUtils.hasAnnotation(handler.getMethod(), Idempotent.class);
                operation.addParametersItem(idempotencyKey(required));
                // Only 2xx responses are stored and replayed (ADR 0014).
                responses.entrySet().stream()
                        .filter(entry -> entry.getKey().startsWith("2") && entry.getValue().get$ref() == null)
                        .forEach(entry -> entry.getValue().addHeaderObject(IdempotencyFilter.REPLAYED_HEADER, new Header()
                                .description("`true` if this is the stored response of an earlier request with the same key.")
                                .schema(new StringSchema()._enum(List.of("true")))));
                responses.putIfAbsent("409", ref(REQUEST_IN_PROGRESS));
                responses.putIfAbsent("413", ref(CONTENT_TOO_LARGE));
                responses.putIfAbsent("422", ref(IDEMPOTENCY_KEY_REUSED));
            }
            responses.putIfAbsent("400", ref(BAD_REQUEST));
            responses.putIfAbsent("429", ref(TOO_MANY_REQUESTS));
            responses.putIfAbsent("500", ref(SERVER_ERROR));
            responses.values().stream().filter(response -> response.get$ref() == null).forEach(response ->
                    response.addHeaderObject(TraceIdFilter.HEADER, traceIdHeader()));
            return operation;
        };
    }

    /**
     * Document-wide corrections: paths as clients call them ({@code /api/v1/...}), and request bodies
     * that reject unknown properties ({@code additionalProperties: false}, ADR 0005), including the
     * objects nested in them. Response schemas stay open, so adding a property isn't a breaking change.
     */
    @Bean
    OpenApiCustomizer versionedPathsAndStrictRequestBodies() {
        return openApi -> {
            if (openApi.getPaths() != null) {
                Paths versioned = new Paths();
                openApi.getPaths().forEach((path, item) -> {
                    Matcher matcher = BARE_VERSION.matcher(path);
                    versioned.addPathItem(matcher.find() ? matcher.replaceFirst("/api/v$1/") : path, item);
                });
                openApi.setPaths(versioned);
                closeRequestBodySchemas(openApi);
            }
        };
    }

    private static List<Parameter> pagingParameters(SortableBy sortable) {
        List<Parameter> parameters = List.of(
                new QueryParameter().name(PageQueryArgumentResolver.PAGE)
                        .description("Zero-based page number. `page` × `size` must not exceed " + PageQuery.MAX_OFFSET
                                + ": narrow the search instead of paging deeper.")
                        .schema(new IntegerSchema().minimum(BigDecimal.ZERO)._default(0)),
                new QueryParameter().name(PageQueryArgumentResolver.SIZE)
                        .description("Page size.")
                        .schema(new IntegerSchema().minimum(BigDecimal.ONE)
                                .maximum(BigDecimal.valueOf(PageQuery.MAX_SIZE))._default(PageQuery.DEFAULT_SIZE)));
        if (sortable == null) {
            return parameters; // the endpoint can't be sorted by the client: a sort parameter is a 400
        }
        List<String> orders = Arrays.stream(sortable.value())
                .flatMap(property -> Stream.of(property, property + ",asc", property + ",desc"))
                .toList();
        ArraySchema sort = new ArraySchema().items(new StringSchema()._enum(orders));
        if (sortable.defaultSort().length > 0) {
            sort.setDefault(List.of(sortable.defaultSort()));
        }
        return Stream.concat(parameters.stream(), Stream.of(new QueryParameter()
                        .name(PageQueryArgumentResolver.SORT)
                        .description("Sort order: a property, optionally followed by `,asc` (default) or `,desc`. "
                                + "Repeat for several orders. Ties are always broken by `" + PageQuery.TIEBREAKER + "`.")
                        .style(Parameter.StyleEnum.FORM).explode(true)
                        .schema(sort)))
                .toList();
    }

    /** Honoured on any {@code POST}/{@code PATCH} (docs/adr/0014-idempotency-keys.md). */
    private static boolean acceptsIdempotencyKey(HandlerMethod handler) {
        RequestMapping mapping = AnnotatedElementUtils.findMergedAnnotation(handler.getMethod(), RequestMapping.class);
        return mapping != null && Arrays.stream(mapping.method())
                .anyMatch(method -> method == RequestMethod.POST || method == RequestMethod.PATCH);
    }

    private static Parameter idempotencyKey(boolean required) {
        return new HeaderParameter().name(IdempotencyKey.HEADER).required(required)
                .description("A unique key for this operation, the same for every retry of it (a UUID is "
                        + "recommended). A retry with the same key and request gets the first response; the key is "
                        + "kept 24 hours. " + (required ? "Required on this operation." : "Optional on this operation."))
                .schema(new StringSchema().minLength(IdempotencyKey.MIN_LENGTH).maxLength(IdempotencyKey.MAX_LENGTH)
                        .example("8e03978e-40d5-43e8-bc93-6894a57f9324"));
    }

    private static void closeRequestBodySchemas(OpenAPI openApi) {
        Map<String, Schema> schemas = openApi.getComponents() != null ? openApi.getComponents().getSchemas() : null;
        if (schemas == null) {
            return;
        }
        Deque<String> pending = new ArrayDeque<>();
        openApi.getPaths().values().stream()
                .flatMap(item -> item.readOperations().stream())
                .filter(operation -> operation.getRequestBody() != null && operation.getRequestBody().getContent() != null)
                .flatMap(operation -> operation.getRequestBody().getContent().values().stream())
                .forEach(media -> collectRefs(media.getSchema(), pending));
        Set<String> closed = new HashSet<>();
        while (!pending.isEmpty()) {
            String name = pending.pop();
            Schema<?> schema = schemas.get(name);
            if (schema != null && closed.add(name) && schema.getProperties() != null) {
                schema.setAdditionalProperties(false);
                schema.getProperties().values().forEach(property -> collectRefs(property, pending));
            }
        }
    }

    private static void collectRefs(Schema<?> schema, Deque<String> refs) {
        if (schema == null) {
            return;
        }
        if (schema.get$ref() != null) {
            refs.push(schema.get$ref().substring(schema.get$ref().lastIndexOf('/') + 1));
        }
        collectRefs(schema.getItems(), refs);
    }

    private static Schema<?> violationSchema() {
        return new ObjectSchema()
                .description("One invalid field or parameter. Exactly one of `pointer` and `parameter` is present.")
                .addProperty("pointer", new StringSchema().description("JSON Pointer to the body field, e.g. `#/salary/min`."))
                .addProperty("parameter", new StringSchema().description("Name of the query, path or header parameter."))
                .addProperty("code", new StringSchema().description("Stable, machine-readable: the constraint "
                        + "(`NotBlank`, `Size`, ...) or `InvalidType`, `UnknownProperty`, `UnknownParameter`, `Required`, `InvalidValue`."))
                .addProperty("detail", new StringSchema().description("English text for developers. The rejected value is never echoed."))
                .required(List.of("code", "detail"));
    }

    private static Schema<?> problemSchema() {
        return new ObjectSchema()
                .description("RFC 9457 Problem Details.")
                .addProperty("type", new StringSchema().format("uri").description("The problem type: compare on this. "
                        + "Absent for a generic HTTP error, where `status` says it all."))
                .addProperty("title", new StringSchema().description("Short summary of the problem type."))
                .addProperty("status", new IntegerSchema().description("The HTTP status code."))
                .addProperty("detail", new StringSchema().description("This occurrence, safe to show to a user."))
                .addProperty("instance", new StringSchema().format("uri-reference").description("The request path."))
                .addProperty("traceId", new StringSchema().description("The request's trace ID (also `X-Trace-Id`): "
                        + "quote it when reporting a problem."))
                .addProperty("errors", new ArraySchema().items(new Schema<>().$ref(VIOLATION_SCHEMA))
                        .description("Only in a `validation-error`: every invalid field or parameter."))
                .required(List.of("title", "status"));
    }

    private static ApiResponse problem(String description) {
        return new ApiResponse().description(description)
                .content(new Content().addMediaType(PROBLEM_JSON,
                        new MediaType().schema(new Schema<>().$ref(PROBLEM_SCHEMA))))
                .addHeaderObject(TraceIdFilter.HEADER, traceIdHeader());
    }

    private static ApiResponse ref(String response) {
        return new ApiResponse().$ref(RESPONSES + response);
    }

    private static Header traceIdHeader() {
        return new Header().description("The request's W3C trace ID, to find its log lines.").schema(new StringSchema());
    }

    private static Header retryAfter() {
        return new Header().description("Seconds to wait before retrying.").schema(new IntegerSchema());
    }
}
